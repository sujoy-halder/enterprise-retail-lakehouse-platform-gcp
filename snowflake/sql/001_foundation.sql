USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RET_PLATFORM_ROLE;
CREATE ROLE IF NOT EXISTS RET_FINANCE_ANALYST_ROLE;
CREATE ROLE IF NOT EXISTS RET_INVENTORY_ANALYST_ROLE;

GRANT ROLE RET_FINANCE_ANALYST_ROLE TO ROLE RET_PLATFORM_ROLE;
GRANT ROLE RET_INVENTORY_ANALYST_ROLE TO ROLE RET_PLATFORM_ROLE;

CREATE DATABASE IF NOT EXISTS RET_ENTERPRISE;
CREATE SCHEMA IF NOT EXISTS RET_ENTERPRISE.FINANCE_MARTS;
CREATE SCHEMA IF NOT EXISTS RET_ENTERPRISE.INVENTORY_MARTS;
CREATE SCHEMA IF NOT EXISTS RET_ENTERPRISE.EXECUTIVE_DASHBOARDS;

CREATE WAREHOUSE IF NOT EXISTS RET_FINANCE_XS_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS RET_INVENTORY_XS_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON DATABASE RET_ENTERPRISE TO ROLE RET_PLATFORM_ROLE;
GRANT USAGE ON SCHEMA RET_ENTERPRISE.FINANCE_MARTS TO ROLE RET_PLATFORM_ROLE;
GRANT USAGE ON SCHEMA RET_ENTERPRISE.INVENTORY_MARTS TO ROLE RET_PLATFORM_ROLE;
GRANT USAGE ON SCHEMA RET_ENTERPRISE.EXECUTIVE_DASHBOARDS TO ROLE RET_PLATFORM_ROLE;
GRANT USAGE ON WAREHOUSE RET_FINANCE_XS_WH TO ROLE RET_PLATFORM_ROLE;
GRANT USAGE ON WAREHOUSE RET_INVENTORY_XS_WH TO ROLE RET_PLATFORM_ROLE;

