USE ROLE RET_PLATFORM_ROLE;
USE DATABASE RET_ENTERPRISE;

CREATE TABLE IF NOT EXISTS FINANCE_MARTS.DAILY_SALES (
  BUSINESS_DATE DATE NOT NULL,
  STORE_ID STRING NOT NULL,
  PRODUCT_ID STRING NOT NULL,
  UNITS_SOLD NUMBER(38, 0) NOT NULL,
  GROSS_REVENUE NUMBER(18, 2) NOT NULL,
  NET_REVENUE NUMBER(18, 2),
  UPDATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS INVENTORY_MARTS.INVENTORY_POSITION (
  SNAPSHOT_DATE DATE NOT NULL,
  STORE_ID STRING NOT NULL,
  SKU STRING NOT NULL,
  ON_HAND_QUANTITY NUMBER(38, 0) NOT NULL,
  RESERVED_QUANTITY NUMBER(38, 0) NOT NULL,
  AVAILABLE_QUANTITY NUMBER(38, 0) NOT NULL,
  UPDATED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE OR REPLACE VIEW EXECUTIVE_DASHBOARDS.SALES_SUMMARY AS
SELECT
  BUSINESS_DATE,
  SUM(UNITS_SOLD) AS UNITS_SOLD,
  SUM(GROSS_REVENUE) AS GROSS_REVENUE,
  SUM(NET_REVENUE) AS NET_REVENUE
FROM FINANCE_MARTS.DAILY_SALES
GROUP BY BUSINESS_DATE;

