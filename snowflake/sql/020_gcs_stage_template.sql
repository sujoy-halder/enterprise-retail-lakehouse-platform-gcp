USE ROLE ACCOUNTADMIN;

-- Replace STORAGE_ALLOWED_LOCATIONS with the gold export bucket URI from Terraform.
CREATE STORAGE INTEGRATION IF NOT EXISTS RET_GCS_INTEGRATION
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = GCS
  ENABLED = TRUE
  STORAGE_ALLOWED_LOCATIONS = ('gcs://REPLACE_GOLD_EXPORT_BUCKET/snowflake/');

DESC STORAGE INTEGRATION RET_GCS_INTEGRATION;

USE ROLE RET_PLATFORM_ROLE;
USE DATABASE RET_ENTERPRISE;

CREATE FILE FORMAT IF NOT EXISTS FINANCE_MARTS.PARQUET_FORMAT
  TYPE = PARQUET
  USE_VECTORIZED_SCANNER = TRUE;

CREATE STAGE IF NOT EXISTS FINANCE_MARTS.GCS_GOLD_STAGE
  URL = 'gcs://REPLACE_GOLD_EXPORT_BUCKET/snowflake/finance/'
  STORAGE_INTEGRATION = RET_GCS_INTEGRATION
  FILE_FORMAT = FINANCE_MARTS.PARQUET_FORMAT;

